// A type-2 entry names an object stream, and its generation is 0 (ISO 32000-1
// 7.5.8.3). Every other entry kind already carries a generation.
func TestXRefStreamCompressedEntryHasGenerationZero(t *testing.T) {
	entry := createXRefTableEntryFromXRefStream(0x02, 5, 7, 3, 0, types.IntSet{}, 0)
	if entry.Generation == nil || *entry.Generation != 0 {
		t.Fatalf("compressed entry generation = %v, want 0", entry.Generation)
	}
	if !entry.Compressed || entry.ObjectStream == nil || *entry.ObjectStream != 7 {
		t.Fatalf("compressed entry = %+v, want object stream 7", entry)
	}
}

// Object 0 must head the free list, and a compressed entry has no offset to
// continue it. The default reader refuses the input with an error and no panic.
func TestCompressedFreeHeadIsRefused(t *testing.T) {
	ctx, err := noRepairRead(compressedFreeHeadPDF, false, model.ValidationStrict)
	if ctx != nil || err == nil {
		t.Fatalf("ctx=%v err=%v; want refusal", ctx != nil, err)
	}
	if !strings.Contains(err.Error(), "free list head obj#0 is compressed") {
		t.Fatalf("error = %q", err)
	}
}

// NoRepair refuses the same head as a repair before the compressed check runs.
func TestCompressedFreeHeadRefusedUnderNoRepair(t *testing.T) {
	_, err := noRepairRead(compressedFreeHeadPDF, true, model.ValidationStrict)
	requireRepairRefused(t, err, model.RepairFreeHead)
}
